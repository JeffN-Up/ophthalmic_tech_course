#!/usr/bin/env node

import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const recommendedReportPath = "launch-evidence/host-dashboard-env-template.md";

function getArgValue(name, fallback = "") {
  const prefix = `--${name}=`;
  const match = process.argv.find(arg => arg.startsWith(prefix));
  return match ? match.slice(prefix.length).trim() : fallback;
}

function getPositionalUrl() {
  return process.argv.find(
    arg => !arg.startsWith("--") && /^https?:\/\//i.test(arg)
  );
}

function normalizePublicAppUrl(value) {
  const trimmedValue = value?.trim() || "";

  if (!trimmedValue) {
    return {
      url: "https://your-domain.example",
      warning:
        "No production URL was provided, so the template keeps the placeholder PUBLIC_APP_URL.",
    };
  }

  try {
    const url = new URL(trimmedValue);
    url.pathname = url.pathname.replace(/\/+$/, "");
    url.search = "";
    url.hash = "";

    const normalizedUrl = url.toString().replace(/\/$/, "");
    const hostname = url.hostname.toLowerCase();
    const warnings = [];

    if (url.protocol !== "https:") {
      warnings.push(
        "PUBLIC_APP_URL should be https before Stripe, email sign-in, sitemap, or buyers use it."
      );
    }

    if (
      hostname === "localhost" ||
      hostname === "127.0.0.1" ||
      hostname === "::1"
    ) {
      warnings.push(
        "PUBLIC_APP_URL points to a local computer. Use the real Render or custom domain for production."
      );
    }

    if (hostname.endsWith(".example") || hostname === "example.com") {
      warnings.push(
        "PUBLIC_APP_URL is still an example domain. Replace it with the real deployed URL."
      );
    }

    return {
      url: normalizedUrl,
      warning: warnings.join(" "),
    };
  } catch {
    return {
      url: "https://your-domain.example",
      warning:
        "The provided PUBLIC_APP_URL could not be parsed, so the template keeps the placeholder.",
    };
  }
}

function getReportPath() {
  const value =
    getArgValue("report-path") ||
    process.env.LAUNCH_ENV_TEMPLATE_REPORT_PATH ||
    "";

  return value ? path.resolve(value) : "";
}

