const publicUrlInput =
  getArgValue("public-app-url") ||
  getPositionalUrl() ||
  process.env.PUBLIC_APP_URL ||
  "";
const { url: publicAppUrl, warning } = normalizePublicAppUrl(publicUrlInput);
const output = renderTemplate({ publicAppUrl, warning });
const reportPath = getReportPath();

if (reportPath) {
  await mkdir(path.dirname(reportPath), { recursive: true });
  await writeFile(reportPath, output, "utf8");
}

console.log(output);

if (reportPath) {
  console.log(`Saved host dashboard template: ${reportPath}`);
}

console.log(`Recommended report path: ${recommendedReportPath}`);
